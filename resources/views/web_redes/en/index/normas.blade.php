                        <h4>MEXICAN STANDARD, Nom 009-STPS-2011.</h4>
                        <p class="hero-p"> ON MAY 06, 2011, NOM-009-STPS-2011, SAFETY CONDITIONS FOR CARRYING OUT WORK AT HEIGHT, WAS PUBLISHED IN THE OFFICIAL GAZETTE OF THE FEDERATION.</p>
                        <p class="hero-p"> The NOM-009-STPS-2011 standard in its article 7 and article 13 establish:</p>
                        <p class="hero-p">7.- General safety measures to carry out work at height</p>
                        <p class="hero-p">7.1 Place on the edges of roofs, terraces, gazebos, galleries or fixed elevated structures, as well as in openings such as perforations, wells, cubes and vertical tunnels: fixed barriers or lateral or perimeter protections, or Safety nets for collective protection against falls of height, in accordance with the provisions of Chapter 13 of this Standard, among other prevention elements, or provide workers with personal systems for work at height, in accordance with the provisions of Chapter 8 of this Standard.</p>
                        <p class="hero-p">13. Safety nets</p>
                        <p class="hero-p">13.1 Safety nets must:</p>
                        <p class="hero-p">
                            a) Be extended at least 2.5 m out of the edge of the work surface and be installed as close as possible below the surface to be protected, but in no case more than 6 m below it;<br>
                            b) Complement the safety net with light cover mesh to protect personnel working at lower levels from falling materials and debris;<br>
                            c) Be installed in accordance with the manufacturer's specifications;<br>
                            Be provided with a high-strength perimeter rope and securing ropes on the edges and ends for anchoring to fixed structures, and<br>
                            e) Be subject to control and maintenance
                        </p>
