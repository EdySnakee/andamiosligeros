                        <h4>NORMA MEXICANA, Nom 009-STPS-2011.</h4>
                        <p class="hero-p"> EL 06 DE MAYO DEL AÑO 2011, SE PUBLICO EN EL DIARIO OFICIAL DE LA FEDERACIÓN LA NOM-009-STPS-2011, CONDICIONES DE SEGURIDAD PARA REALIZAR TRABAJOS EN ALTURA.</p>
                        <p class="hero-p"> La norma NOM-009-STPS-2011 en su articulo 7 y el articulo 13 establecen:</p>
                        <p class="hero-p">7.- Medidas generales de seguridad para realizar trabajos en altura</p>
                        <p class="hero-p">7.1 Colocar en bordes de azoteas, terrazas, miradores, galerías o estructuras fijas elevadas, al igual que en aberturas como perforaciones, pozos, cubos y túneles verticales: barreras fijas o protecciones laterales o perimetrales, o Mallas de seguridad para protección colectiva contra caídas de altura, de conformidad con lo dispuesto en el Capítulo 13 de esta Norma, entre otros elementos de prevención, o bien proveer a los trabajadores de sistemas personales para trabajos en altura, de acuerdo con lo establecido en el Capítulo 8 de la presente Norma.</p>
                        <p class="hero-p">13. Mallas de seguridad</p>
                        <p class="hero-p">13.1 Las Mallas de seguridad, deberán:</p>
                        <p class="hero-p">
                            a) Estar extendidas por lo menos 2.5 m hacia afuera del borde de la superficie de trabajo y ser instaladas lo más cerca posible bajo la superficie que se requiere proteger, pero en ningún caso a más de 6 m por debajo de ésta; <br>
                            b) Complementar la red de seguridad con Mallas de cubierta ligera para proteger al personal que trabaje en niveles inferiores de la caída de materiales y escombros;<br>
                            c) Estar instaladas de acuerdo con las especificaciones del fabricante;<br>
                            d) Estar provistas de una cuerda perimetral de alta resistencia y cuerdas de sujeción en orillas y extremos para el anclaje a estructuras fijas, y<br>
                            e) Estar sujetas a control y mantenimiento
                        </p>
